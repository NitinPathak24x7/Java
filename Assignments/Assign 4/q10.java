// To check whether a number is divisble by 5 or 7 or neither
public class q10 {
    public static void main(String [] args){
        int x=367;
        if(x%5==0)
            System.out.println("The number is divisible by 5");
        else if(x%7==0)
            System.out.println("The number is divisible by 7");
        else
            System.out.println("The number is neither divisible by 5 nor 7");

    }
}
