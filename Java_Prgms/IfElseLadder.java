public class IfElseLadder{
    public static void main (String[] args){
        int num=65;

        if(90<=num){
            System.out.println("A");
        }
        else if(80<=num){
            System.out.println("B");
        }
        else if(70<=num){
            System.out.println("C");
        }
        else if(60<=num){
            System.out.println("D");
        }
        else if(50<=num){
            System.out.println("E");
        }
        else if(50>=num){
            System.out.println("F");
        }

        }
        
    }
    

